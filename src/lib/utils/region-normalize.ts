/**
 * 将任意区域输入字符串归一化为 customers/page.tsx regionOptions 中的规范值。
 * 无法识别的值（大区/销售区域/垃圾数据）原样返回。
 */
export function normalizeRegionToChinese(input: string | null | undefined): string | null {
  if (!input) return null;
  const trimmed = input.trim();
  if (!trimmed) return null;
  return REGION_ALIAS_MAP[trimmed] ?? trimmed;
}

/**
 * 判断给定值是否为规范 regionOptions 中的合法值
 * （用于导入校验或 UI 告警）
 */
export const VALID_REGION_VALUES = new Set(Object.values(REGION_ALIAS_MAP));

export function isValidRegionValue(value: string): boolean {
  return VALID_REGION_VALUES.has(value);
}
